COMPOSED_MODES = frozenset({MODE_DISH_TEXT, MODE_DISH_COMBINED})


def _dish_head(name: str, weight_g: float) -> str:
    return f'Блюдо: "{name}", вес порции: {weight_g} г.'


def user_preamble(
    mode: str,
    *,
    text: str | None = None,
    caption: str = "",
    dish_name: str | None = None,
    weight_g: float | None = None,
) -> str:
    """Текстовая часть user-сообщения под режим (ТЗ §4.3, таблица).

    Системный промпт один на все режимы; различается только это. Так режим
    перестаёт быть отдельной контрактной моделью и становится параметром.
    """
    if mode == MODE_DIARY:
        return (text or "").strip() or caption.strip() or DIARY_PHOTO_FALLBACK
    if mode == MODE_DISH_TEXT:
        return (
            f"{_dish_head(dish_name or '', weight_g or 0)}\n"
            f"Состав: {(text or '').strip()}.\n"
            "Верни запись НА КАЖДЫЙ ингредиент состава с его per100g и portion_g "
            "из текста. Итог посчитает программа."
        )
    if mode == MODE_DISH_PHOTOS:
        return (
            f"{_dish_head(dish_name or '', weight_g or 0)}\n"
            "На снимках — это блюдо. Верни ОДНУ запись: per100g блюда, "
            "portion_g = null."
        )
    if mode == MODE_DISH_COMBINED:
        return (
            f"{_dish_head(dish_name or '', weight_g or 0)}\n"
            f"Состав с граммовками: {(text or '').strip()}.\n"
            "На снимках — этикетки ингредиентов. Для каждого ингредиента из "
            "состава верни отдельную запись: per100g с его этикетки (если нашёл) "
            "и portion_g из состава. Не складывай — итог посчитает программа."
        )
    raise ValueError(f"неизвестный режим разбора: {mode}")
