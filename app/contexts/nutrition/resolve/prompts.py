MODES = (MODE_DIARY, MODE_DISH_TEXT, MODE_DISH_PHOTOS, MODE_DISH_COMBINED)

# Режимы, где итог собирается из НЕСКОЛЬКИХ позиций по их граммовкам (§5.4.b).
