# Режимы разбора. Все пять путей ТЗ §4.3: дневник (текст/фото) отличается только
# наличием снимков, поэтому режимов четыре, а путей пять.
MODE_DIARY = "diary"
MODE_DISH_TEXT = "dish_text"
MODE_DISH_PHOTOS = "dish_photos"
